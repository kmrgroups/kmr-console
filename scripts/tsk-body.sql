create table if not exists console.tsk_tasks (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  no text not null, title text not null, detail text, assignee text, assignee_name text, assigned_by text, assigned_by_name text,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  status text not null default 'open' check (status in ('open', 'progress', 'blocked', 'done', 'cancelled')),
  due date, done_at timestamptz, tags text, checklist jsonb not null default '[]',
  source_app text, source_ref text, source_label text, source_url text, source_key text,
  last_due_note date, sample boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique (customer_id, no));
create unique index if not exists tsk_source_key on console.tsk_tasks (customer_id, source_key) where source_key is not null;
create index if not exists tsk_assignee on console.tsk_tasks (customer_id, assignee, status);
create index if not exists tsk_due on console.tsk_tasks (customer_id, due) where status in ('open', 'progress', 'blocked');
create table if not exists console.tsk_comments (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  task_id uuid not null references console.tsk_tasks(id) on delete cascade, author text not null, author_name text, body text not null, kind text not null default 'comment',
  sample boolean not null default false, created_at timestamptz not null default now());
create index if not exists tsk_comments_task on console.tsk_comments (task_id, created_at);
create table if not exists console.tsk_notifications (
