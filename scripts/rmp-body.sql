-- everything the screens need for one month, in one call
create or replace function public.kmr_rmp_load(p_slug text, p_month text) returns jsonb
language plpgsql stable security definer set search_path = console, public as $$
declare cid uuid := console.qp_cid(p_slug, 'rmp'); cap boolean;
begin
  if p_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Month must look like 2026-10.'; end if;
  cap := exists (select 1 from console.licences where customer_id = cid and product_code = 'capacity' and product_ref is not null);
  return jsonb_build_object(
    'parts', coalesce((select jsonb_agg(jsonb_build_object('code', r.code, 'name', r.name) || r.data order by r.code) from console.ops_records r where r.customer_id = cid and r.kind = 'parts' and r.active), '[]'),
    'materials', coalesce((select jsonb_agg(jsonb_build_object('code', r.code, 'name', r.name) || r.data order by r.code) from console.ops_records r where r.customer_id = cid and r.kind = 'raw_materials' and r.active), '[]'),
    'suppliers', coalesce((select jsonb_agg(jsonb_build_object('code', r.code, 'name', r.name) || r.data order by r.code) from console.ops_records r where r.customer_id = cid and r.kind = 'suppliers' and r.active), '[]'),
    'bom', coalesce((select jsonb_agg(to_jsonb(b) - 'customer_id' order by b.part_code, b.material_code) from console.rmp_bom b where b.customer_id = cid), '[]'),
    'stock', coalesce((select jsonb_agg(to_jsonb(s) - 'customer_id' order by s.material_code) from console.rmp_stock s where s.customer_id = cid), '[]'),
    'demand', coalesce((select jsonb_agg(to_jsonb(d) - 'customer_id' order by d.part_code) from console.rmp_demand d where d.customer_id = cid and d.month = p_month), '[]'),
    'months', coalesce((select jsonb_agg(m order by m desc) from (select distinct month m from console.rmp_demand where customer_id = cid) x), '[]'),
    'orders', coalesce((select jsonb_agg(to_jsonb(o) - 'customer_id' order by o.created_at desc) from console.rmp_orders o
                         where o.customer_id = cid and (o.status in ('planned', 'ordered') or o.updated_at > now() - interval '120 days')), '[]'),
    'capacity', cap,
    'today', (now() at time zone 'Asia/Kolkata')::date);
end $$;
grant execute on function public.kmr_rmp_load(text, text) to authenticated;

-- ---------- bill of material ----------
create or replace function public.kmr_rmp_bom_save(p_slug text, p jsonb) returns uuid
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp'); rid uuid; pc text := trim(coalesce(p ->> 'part_code', '')); mc text := trim(coalesce(p ->> 'material_code', ''));
begin
  if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'parts' and code = pc) then raise exception 'Part % is not in Operations Master › Parts.', pc; end if;
  if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'raw_materials' and code = mc) then raise exception 'Material % is not in Operations Master › Raw material.', mc; end if;
  insert into console.rmp_bom (customer_id, part_code, material_code, rm_kg, loss_pct, notes, updated_by)
  values (cid, pc, mc, nullif(p ->> 'rm_kg', '')::numeric, coalesce(nullif(p ->> 'loss_pct', '')::numeric, 0), nullif(p ->> 'notes', ''), lower(coalesce(auth.jwt() ->> 'email', '')))
  on conflict (customer_id, part_code, material_code) do update set rm_kg = excluded.rm_kg, loss_pct = excluded.loss_pct, notes = excluded.notes, updated_by = excluded.updated_by, updated_at = now(), sample = false
  returning id into rid;
  return rid;
end $$;
create or replace function public.kmr_rmp_bom_delete(p_slug text, p_id uuid) returns void
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp');
begin delete from console.rmp_bom where id = p_id and customer_id = cid; end $$;
grant execute on function public.kmr_rmp_bom_save(text, jsonb), public.kmr_rmp_bom_delete(text, uuid) to authenticated;

