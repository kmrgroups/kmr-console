-- ---------- tables ----------
create table if not exists console.rmp_bom (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  part_code text not null, material_code text not null,
  rm_kg numeric check (rm_kg is null or rm_kg >= 0),            -- raw material per piece before loss; blank = the part's weight from the Operations Master
  loss_pct numeric not null default 0 check (loss_pct >= 0 and loss_pct < 100),   -- bar end, parting, chips, forging flash — on top of rm_kg
  notes text, sample boolean not null default false, updated_by text, updated_at timestamptz not null default now(),
  unique (customer_id, part_code, material_code));
create table if not exists console.rmp_stock (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  material_code text not null,
  on_hand_kg numeric not null default 0 check (on_hand_kg >= 0), safety_kg numeric not null default 0 check (safety_kg >= 0),
  lead_days int check (lead_days is null or lead_days >= 0), moq_kg numeric check (moq_kg is null or moq_kg >= 0), pack_kg numeric check (pack_kg is null or pack_kg >= 0),
  sample boolean not null default false, updated_by text, updated_at timestamptz not null default now(),
  unique (customer_id, material_code));
create table if not exists console.rmp_demand (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  month text not null check (month ~ '^\d{4}-(0[1-9]|1[0-2])$'), part_code text not null,
  start_qty numeric not null check (start_qty >= 0), sales_qty numeric, need_by date,
  source text not null default 'capacity' check (source in ('capacity', 'manual')),       -- manual wins: a published plan never overwrites a typed quantity
  sample boolean not null default false, published_by text, published_at timestamptz not null default now(),
  unique (customer_id, month, part_code));
create table if not exists console.rmp_orders (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  material_code text not null, supplier_code text, month text, po_no text,
  qty_kg numeric not null check (qty_kg > 0), rate numeric, order_date date, due_date date,
  status text not null default 'planned' check (status in ('planned', 'ordered', 'received', 'cancelled')),
  received_kg numeric, received_on date, notes text,
  sample boolean not null default false, updated_by text, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
