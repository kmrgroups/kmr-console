declare cid uuid := console.qp_edit(p_slug, 'rmp');
begin delete from console.rmp_demand where customer_id = cid and month = p_month and part_code = p_part; end $$;
grant execute on function public.kmr_rmp_demand_save(text, text, jsonb), public.kmr_rmp_demand_clear(text, text, text) to authenticated;

-- ---------- the Capacity Planner publishes its parts to start (called after every save of the plan; silent when the company has no Raw Material Planning) ----------
create or replace function public.kmr_rmp_publish(p_org uuid, p_month text, p_rows jsonb) returns integer
language plpgsql security definer set search_path = console, public as $$
declare cid uuid; r jsonb; n int := 0; me text := lower(coalesce(auth.jwt() ->> 'email', '')); keep text[] := '{}';
begin
  if p_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then return 0; end if;
  select l.customer_id into cid from console.licences l where l.product_code = 'capacity' and l.product_ref = p_org limit 1;
  if cid is null or not exists (select 1 from console.licences where customer_id = cid and product_code = 'rmp') then return 0; end if;
  if not coalesce((select ok from console.access_state('rmp', cid)), false) then return 0; end if;
  if coalesce(public.cp_my_role(p_org), '') not in ('admin', 'editor') then return 0; end if;
  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    continue when coalesce(r ->> 'part_code', '') = '';
    keep := keep || (r ->> 'part_code');
    insert into console.rmp_demand (customer_id, month, part_code, start_qty, sales_qty, need_by, source, published_by)
    values (cid, p_month, r ->> 'part_code', greatest(0, coalesce(nullif(r ->> 'start_qty', '')::numeric, 0)), nullif(r ->> 'sales_qty', '')::numeric, nullif(r ->> 'need_by', '')::date, 'capacity', me)
    on conflict (customer_id, month, part_code) do update set start_qty = excluded.start_qty, sales_qty = excluded.sales_qty, need_by = excluded.need_by, published_by = excluded.published_by, published_at = now(), sample = false
      where console.rmp_demand.source = 'capacity';
    n := n + 1;
  end loop;
  delete from console.rmp_demand where customer_id = cid and month = p_month and source = 'capacity' and not (part_code = any (keep));   -- parts that left the plan
  return n;
end $$;
grant execute on function public.kmr_rmp_publish(uuid, text, jsonb) to authenticated;

-- ---------- orders ----------
create or replace function public.kmr_rmp_order_save(p_slug text, p jsonb) returns uuid
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp'); rid uuid := nullif(p ->> 'id', '')::uuid; mc text := trim(coalesce(p ->> 'material_code', '')); st text;
begin
  perform console.require_feature(p_slug, 'rmp', 'rmp.supplier-orders-receipts');
  if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'raw_materials' and code = mc) then raise exception 'Material % is not in Operations Master › Raw material.', mc; end if;
  if coalesce(nullif(p ->> 'qty_kg', '')::numeric, 0) <= 0 then raise exception 'Enter the quantity in kg.'; end if;
  if rid is null then
    insert into console.rmp_orders (customer_id, material_code, supplier_code, month, po_no, qty_kg, rate, order_date, due_date, status, notes, updated_by)
    values (cid, mc, nullif(p ->> 'supplier_code', ''), nullif(p ->> 'month', ''), nullif(p ->> 'po_no', ''), (p ->> 'qty_kg')::numeric, nullif(p ->> 'rate', '')::numeric,
            nullif(p ->> 'order_date', '')::date, nullif(p ->> 'due_date', '')::date, case when p ->> 'status' = 'ordered' then 'ordered' else 'planned' end, nullif(p ->> 'notes', ''), lower(coalesce(auth.jwt() ->> 'email', '')))
    returning id into rid;
  else
    select status into st from console.rmp_orders where id = rid and customer_id = cid;
    if st is null then raise exception 'Unknown order.'; end if;
    if st in ('received', 'cancelled') then raise exception 'A % order cannot be changed.', st; end if;
    update console.rmp_orders set supplier_code = nullif(p ->> 'supplier_code', ''), po_no = nullif(p ->> 'po_no', ''), qty_kg = (p ->> 'qty_kg')::numeric, rate = nullif(p ->> 'rate', '')::numeric,
           order_date = nullif(p ->> 'order_date', '')::date, due_date = nullif(p ->> 'due_date', '')::date, notes = nullif(p ->> 'notes', ''),
           updated_by = lower(coalesce(auth.jwt() ->> 'email', '')), updated_at = now(), sample = false
     where id = rid and customer_id = cid;
  end if;
  return rid;
end $$;
-- planned → ordered → received (the received kg is added to the stock) · or cancelled
create or replace function public.kmr_rmp_order_status(p_slug text, p_id uuid, p_status text, p_received_kg numeric default null) returns text
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp'); o console.rmp_orders%rowtype; today date := (now() at time zone 'Asia/Kolkata')::date; kg numeric;
begin
  perform console.require_feature(p_slug, 'rmp', 'rmp.supplier-orders-receipts');
  select * into o from console.rmp_orders where id = p_id and customer_id = cid for update;
  if o.id is null then raise exception 'Unknown order.'; end if;
  if p_status not in ('ordered', 'received', 'cancelled') then raise exception 'Unknown status.'; end if;
  if o.status in ('received', 'cancelled') then raise exception 'This order is already %.', o.status; end if;
  if p_status = 'ordered' then
    update console.rmp_orders set status = 'ordered', order_date = coalesce(order_date, today), updated_at = now(), updated_by = lower(coalesce(auth.jwt() ->> 'email', '')) where id = p_id;
  elsif p_status = 'cancelled' then
    update console.rmp_orders set status = 'cancelled', updated_at = now(), updated_by = lower(coalesce(auth.jwt() ->> 'email', '')) where id = p_id;
  else
    kg := coalesce(p_received_kg, o.qty_kg);
    if kg <= 0 then raise exception 'Enter the quantity received.'; end if;
    update console.rmp_orders set status = 'received', received_kg = kg, received_on = today, updated_at = now(), updated_by = lower(coalesce(auth.jwt() ->> 'email', '')) where id = p_id;
    insert into console.rmp_stock (customer_id, material_code, on_hand_kg, updated_by) values (cid, o.material_code, kg, lower(coalesce(auth.jwt() ->> 'email', '')))
    on conflict (customer_id, material_code) do update set on_hand_kg = console.rmp_stock.on_hand_kg + kg, updated_at = now(), updated_by = excluded.updated_by;
  end if;
  return p_status;
end $$;
create or replace function public.kmr_rmp_order_delete(p_slug text, p_id uuid) returns void
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp');
begin
  perform console.require_feature(p_slug, 'rmp', 'rmp.supplier-orders-receipts');
  delete from console.rmp_orders where id = p_id and customer_id = cid and status = 'planned';
end $$;
grant execute on function public.kmr_rmp_order_save(text, jsonb), public.kmr_rmp_order_status(text, uuid, text, numeric), public.kmr_rmp_order_delete(text, uuid) to authenticated;

-- ---------- sample data: built from the Operations Master sample parts and raw materials ----------
create or replace function console.rmp_sample(p_cid uuid, p_action text) returns integer language plpgsql security definer set search_path = console, public as $$
declare today date := (now() at time zone 'Asia/Kolkata')::date; mth text := to_char((now() at time zone 'Asia/Kolkata')::date, 'YYYY-MM'); n int := 0; k int := 0; p record; m record;
begin
  if p_action = 'flush' then
    delete from console.rmp_orders where customer_id = p_cid and sample; get diagnostics k = row_count; n := n + k;
    delete from console.rmp_demand where customer_id = p_cid and sample; get diagnostics k = row_count; n := n + k;
    delete from console.rmp_bom where customer_id = p_cid and sample; get diagnostics k = row_count; n := n + k;
    delete from console.rmp_stock where customer_id = p_cid and sample; get diagnostics k = row_count; n := n + k;
    return n;
  end if;
  if exists (select 1 from console.rmp_stock where customer_id = p_cid and sample) then return 0; end if;
  -- stock, safety stock, lead time, MOQ and pack for every sample raw material
  for m in select r.code, r.data, row_number() over (order by r.code) rn from console.ops_records r where r.customer_id = p_cid and r.kind = 'raw_materials' and r.sample and r.active loop
    insert into console.rmp_stock (customer_id, material_code, on_hand_kg, safety_kg, lead_days, moq_kg, pack_kg, sample, updated_by)
    values (p_cid, m.code, (array[2400, 5200, 900, 3100, 1800, 4200, 2600])[1 + (m.rn - 1) % 7], (array[800, 1500, 400, 1000, 600, 1200, 900])[1 + (m.rn - 1) % 7],
            case m.data ->> 'form' when 'Bar' then 10 when 'Forging' then 21 else 28 end, case m.data ->> 'form' when 'Bar' then 1000 else 2000 end, case m.data ->> 'form' when 'Bar' then 250 else 500 end, true, 'sample');
    n := n + 1;
  end loop;
  -- parts to start this month (as the Capacity Planner would publish them) and a bill of material with a loss % on the bar parts
  for p in select r.code, r.data, row_number() over (order by r.code) rn from console.ops_records r where r.customer_id = p_cid and r.kind = 'parts' and r.sample and r.active loop
