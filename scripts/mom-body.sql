create table if not exists console.mom_counters (
  customer_id uuid not null references console.customers(id) on delete cascade, key text not null, n bigint not null default 0, sample boolean not null default false, primary key (customer_id, key));
create table if not exists console.mom_meetings (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  meeting_no text not null, title text not null, mtype text, meeting_date date not null, start_time text, end_time text, venue text, chairperson text, scribe text,
  language text not null default 'en-IN', attendees jsonb not null default '[]', agenda text, prev_ref text, next_date date, distribution text,
  status text not null default 'open' check (status in ('open', 'closed', 'void')), void_reason text, closed_by text, closed_at timestamptz,
  sample boolean not null default false, created_by text, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique (customer_id, meeting_no));
create table if not exists console.mom_points (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  meeting_id uuid not null references console.mom_meetings(id) on delete cascade, seq int not null default 1,
  topic text, what text not null, why text, who text, when_on date, when_note text, where_at text, how text,
  ptype text not null default 'Discussion' check (ptype in ('Discussion', 'Decision', 'Action', 'Information', 'Risk / concern', 'Query')),
  status text not null default 'Open' check (status in ('Open', 'In progress', 'Done', 'Dropped')),
  lang text, remarks text, source text not null default 'typed' check (source in ('typed', 'voice')),
  seg_ids jsonb not null default '[]', translations jsonb not null default '{}',
  sample boolean not null default false, created_by text, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists console.mom_segments (
  id uuid primary key default gen_random_uuid(), customer_id uuid not null references console.customers(id) on delete cascade,
  meeting_id uuid not null references console.mom_meetings(id) on delete cascade, client_id text not null,
  lang text, text text not null, spoken_at timestamptz not null default now(), speaker text,
  point_id uuid references console.mom_points(id) on delete set null,
  sample boolean not null default false, created_by text, created_at timestamptz not null default now(),
  unique (meeting_id, client_id));
create index if not exists mom_meet_date on console.mom_meetings (customer_id, meeting_date desc);
create index if not exists mom_pt_meet on console.mom_points (meeting_id, seq);
create index if not exists mom_pt_open on console.mom_points (customer_id, status, when_on);
create index if not exists mom_seg_meet on console.mom_segments (meeting_id, spoken_at);
