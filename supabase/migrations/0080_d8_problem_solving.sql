create or replace function public.kmr_grand_real_import(p_slug text, p_data jsonb) returns jsonb
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.grand_customer(p_slug); out jsonb := '{}'; t text; a jsonb; n int; me text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if p_data ->> 'format' is distinct from 'kmr-real-data' then raise exception 'This is not a Grand Master real-data file.'; end if;
  if lower(coalesce(p_data ->> 'company', '')) <> lower(p_slug) then
    raise exception 'This file is a backup of another company (%).', p_data ->> 'company';
  end if;
  foreach t in array array['hrm','pd','capacity'] loop
    a := p_data -> 'apps' -> t;
    if a is null or console.grand_ref(cid, t) is null then continue; end if;
    out := out || jsonb_build_object(t, public.kmr_data_import(p_slug, t, a) -> 'restored');
    if t = 'hrm' then
      select count(*) into n from hrm.employees where tenant_id = console.grand_ref(cid, 'hrm') and coalesce(email, '') not like '%@demo.kmr.test';
      out := out || jsonb_build_object('hrm', n, 'hrm_candidates', console.grand_hrm_real_candidates(console.grand_ref(cid, 'hrm')));
    end if;
  end loop;
  a := p_data -> 'apps' -> 'balloon';
  if a is not null and console.grand_ref(cid, 'balloon') is not null then
    perform public.kmr_balloon_own_flush(p_slug);
    if jsonb_array_length(coalesce(a -> 'tables' -> 'bi_reports', '[]')) > 0 then
      out := out || jsonb_build_object('balloon', public.kmr_balloon_own_load(p_slug, a));
    else out := out || jsonb_build_object('balloon', 0); end if;
  end if;
  -- Operations Master before Sales Flow / Calibration Hub (they point at its parts and gauges by code)
  a := p_data -> 'apps' -> 'ops';
  if a is not null then
    delete from console.ops_records where customer_id = cid and not sample;
    insert into console.ops_records (customer_id, kind, code, name, data, active, sample, updated_by)
    select cid, x ->> 'kind', x ->> 'code', coalesce(x ->> 'name', x ->> 'code'), coalesce(x -> 'data', '{}'), coalesce((x ->> 'active')::boolean, true), false, me
      from jsonb_array_elements(coalesce(a -> 'records', '[]')) x
     where coalesce(x ->> 'kind', '') <> '' and coalesce(x ->> 'code', '') <> ''
    on conflict (customer_id, kind, code) do update set name = excluded.name, data = excluded.data, active = excluded.active, sample = false, updated_by = me;
    get diagnostics n = row_count; out := out || jsonb_build_object('ops', n);
  end if;
  foreach t in array array['sales','calib','apqp','ppap','rmp','mmd','mnt','mom','cad','hrms','tsk','msa','spc','crm','d8'] loop
    a := p_data -> 'apps' -> t;
    if a is null or not console.has_app(cid, t) then continue; end if;
    perform console.app2_restore(t, cid, a -> 'tables', true);
    if t = 'sales' then select count(*) into n from console.sf_lines where customer_id = cid and not sample;
    elsif t = 'calib' then select count(*) into n from console.cal_instruments where customer_id = cid and not sample;
    elsif t = 'apqp' then select count(*) into n from console.apqp_projects where customer_id = cid and not sample;
    elsif t = 'ppap' then select count(*) into n from console.ppap_submissions where customer_id = cid and not sample;
    elsif t = 'rmp' then select count(*) into n from console.rmp_stock where customer_id = cid and not sample;
    elsif t = 'mmd' then select count(*) into n from console.mmd_route_sheets where customer_id = cid and not sample;
    elsif t = 'mnt' then select count(*) into n from console.mnt_breakdowns where customer_id = cid and not sample;
    elsif t = 'mom' then select count(*) into n from console.mom_meetings where customer_id = cid and not sample;
    elsif t = 'cad' then select count(*) into n from console.cad_drawings where customer_id = cid and not sample;
    elsif t = 'hrms' then select count(*) into n from console.hrms_employees where customer_id = cid and not sample;
    elsif t = 'tsk' then select count(*) into n from console.tsk_tasks where customer_id = cid and not sample;
    elsif t = 'msa' then select count(*) into n from console.msa_studies where customer_id = cid and not sample;
    elsif t = 'spc' then select count(*) into n from console.spc_charts where customer_id = cid and not sample;
    elsif t = 'crm' then select count(*) into n from console.crm_parties where customer_id = cid and not sample;
    else select count(*) into n from console.d8_reports where customer_id = cid and not sample; end if;
    out := out || jsonb_build_object(t, n);
  end loop;
  return out;
end $$;
revoke all on function public.kmr_grand_real_import(text, jsonb) from public, anon;
grant execute on function public.kmr_grand_real_import(text, jsonb) to authenticated;

create or replace function console.app2_export(p_app text, p_cid uuid, p_real_only boolean) returns jsonb
language plpgsql stable security definer set search_path = console, public as $$
declare t text; rows jsonb; tabs jsonb := '{}'; parent text;
begin
  foreach t in array console.app2_tables(p_app) loop
    parent := case when t in ('sf_lines','sf_actions','cal_instruments','apqp_projects','ppap_submissions','rmp_bom','rmp_stock','rmp_demand','rmp_orders','mmd_counters','mmd_route_sheets','mmd_tags','mmd_dcs','mmd_entries','mmd_defects','mmd_grns','mmd_loss','mnt_counters','mnt_breakdowns','mnt_pm_plans','mnt_pm_log','mnt_events','mom_counters','mom_meetings','mom_points','mom_segments','cad_counters','cad_drawings') or t like 'crm\_%' or t like 'd8\_%' then null when p_app = 'sales' then 'sf_lines' when p_app = 'calib' then 'cal_instruments' else 'apqp_projects' end;
    if not p_real_only then
      execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''customer_id''), ''[]'') from console.%I x where x.customer_id = $1', t) into rows using p_cid;
    elsif parent is null then
      execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''customer_id''), ''[]'') from console.%I x where x.customer_id = $1 and not x.sample', t) into rows using p_cid;
    else
      execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''customer_id''), ''[]'') from console.%I x join console.%I p on p.id = x.%I where x.customer_id = $1 and not p.sample',
                     t, parent, case parent when 'sf_lines' then 'line_id' when 'apqp_projects' then 'project_id' else 'instrument_id' end) into rows using p_cid;
    end if;
    tabs := tabs || jsonb_build_object(t, rows);
  end loop;
  return tabs;
end $$;
revoke all on function console.app2_export(text, uuid, boolean), console.app2_clear(text, uuid, boolean), console.app2_restore(text, uuid, jsonb, boolean) from public, anon, authenticated;

-- the developer sample-data button knows the new app
create or replace function public.kmr_app_sample(p_slug text, p_app text, p_action text) returns jsonb
language plpgsql security definer set search_path = console, public as $$
declare cid uuid; r uuid; out jsonb := '{}'; n int;
begin
  if not coalesce(console.is_staff(), false) then raise exception 'Only the KMR developer login can load or remove sample data here.'; end if;
  if p_action not in ('load', 'flush') then raise exception 'Unknown action.'; end if;
  select id into cid from console.customers where slug = lower(p_slug);
  if cid is null then raise exception 'Unknown company link.'; end if;
  if p_app = 'hrm' then p_app := 'hrms'; end if;
  if not console.has_app(cid, p_app) then raise exception 'This company does not have that app.'; end if;
  if p_app in ('sales', 'calib') and p_action = 'load' then
    perform public.kmr_ops_sample_load(p_slug);                 -- built from the Operations Master sample parts, contracts and gauges
  end if;
  if p_app = 'balloon' then out := jsonb_build_object('balloon', public.kmr_ops_sample_drawing(p_slug, p_action));
  elsif p_app in ('pd', 'capacity') then
    if p_action = 'load' then out := jsonb_build_object('operations_master', (public.kmr_ops_sample_load(p_slug) ->> 'added')::int);
    else out := jsonb_build_object('operations_master', public.kmr_ops_sample_flush(p_slug)); end if;
  elsif p_app = 'sales' then out := jsonb_build_object('sales', console.sf_sample(cid, p_action));
  elsif p_app = 'calib' then out := jsonb_build_object('calib', console.cal_sample(cid, p_action));
  elsif p_app = 'apqp' then out := jsonb_build_object('apqp', console.apqp_sample(cid, p_action));
  elsif p_app = 'ppap' then out := jsonb_build_object('ppap', console.ppap_sample(cid, p_action));
  elsif p_app = 'rmp' then out := jsonb_build_object('rmp', console.rmp_sample(cid, p_action));
  elsif p_app = 'mmd' then out := jsonb_build_object('mmd', console.mmd_sample(cid, p_action));
  elsif p_app = 'mnt' then out := jsonb_build_object('mnt', console.mnt_sample(cid, p_action));
  elsif p_app = 'mom' then out := jsonb_build_object('mom', console.mom_sample(cid, p_action));
  elsif p_app = 'cad' then out := jsonb_build_object('cad', console.cad_sample(cid, p_action));
  elsif p_app = 'hrms' then out := jsonb_build_object('hrms', console.hrms_sample(cid, p_action));
  elsif p_app = 'tsk' then out := jsonb_build_object('tsk', console.tsk_sample(cid, p_action));
  elsif p_app = 'msa' then out := jsonb_build_object('msa', console.msa_sample(cid, p_action));
  elsif p_app = 'spc' then out := jsonb_build_object('spc', console.spc_sample(cid, p_action));
  elsif p_app = 'crm' then out := jsonb_build_object('crm', console.crm_sample(cid, p_action));
  elsif p_app = 'd8' then out := jsonb_build_object('d8', console.d8_sample(cid, p_action));
  else raise exception 'No sample data is defined for this app.'; end if;
  return out;
end $$;
