create or replace function public.kmr_rmp_bom_save(p_slug text, p jsonb) returns uuid
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp'); rid uuid; pc text := trim(coalesce(p ->> 'part_code', '')); mc text := trim(coalesce(p ->> 'material_code', ''));
begin
  if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'parts' and code = pc) then raise exception 'Part % is not in Operations Master › Parts.', pc; end if;
  if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'raw_materials' and code = mc) then raise exception 'Material % is not in Operations Master › Raw material.', mc; end if;
  insert into console.rmp_bom (customer_id, part_code, material_code, rm_kg, loss_pct, notes, updated_by)
  values (cid, pc, mc, nullif(p ->> 'rm_kg', '')::numeric, coalesce(nullif(p ->> 'loss_pct', '')::numeric, 0), nullif(p ->> 'notes', ''), lower(coalesce(auth.jwt() ->> 'email', '')))
  on conflict (customer_id, part_code, material_code) do update set rm_kg = excluded.rm_kg, loss_pct = excluded.loss_pct, notes = excluded.notes, updated_by = excluded.updated_by, updated_at = now(), sample = false
  returning id into rid;
  return rid;
end $$;
