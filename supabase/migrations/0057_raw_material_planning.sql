-- ---------- parts to start: typed by hand (a typed quantity is never overwritten by the Capacity Planner) ----------
create or replace function public.kmr_rmp_demand_save(p_slug text, p_month text, p_rows jsonb) returns integer
language plpgsql security definer set search_path = console, public as $$
declare cid uuid := console.qp_edit(p_slug, 'rmp'); r jsonb; n int := 0;
begin
  if p_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then raise exception 'Month must look like 2026-10.'; end if;
  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    if not exists (select 1 from console.ops_records where customer_id = cid and kind = 'parts' and code = trim(coalesce(r ->> 'part_code', ''))) then
      raise exception 'Part % is not in Operations Master › Parts.', r ->> 'part_code';
    end if;
    insert into console.rmp_demand (customer_id, month, part_code, start_qty, need_by, source, published_by)
    values (cid, p_month, trim(r ->> 'part_code'), greatest(0, coalesce(nullif(r ->> 'start_qty', '')::numeric, 0)), nullif(r ->> 'need_by', '')::date, 'manual', lower(coalesce(auth.jwt() ->> 'email', '')))
    on conflict (customer_id, month, part_code) do update set start_qty = excluded.start_qty, need_by = excluded.need_by, source = 'manual', published_by = excluded.published_by, published_at = now(), sample = false;
    n := n + 1;
  end loop;
  return n;
end $$;
