-- 0058 — MMD: Material Movement & Data (a new KMR App)
--  • Raw material is issued from the RM store against a route sheet; every issue, every process and every supplier movement carries a QR tag.
--  • The route (process sequence) comes from the Operations Master › Cycle times (op no., machine, in-house or supplier process).
--  • Scan a tag → enter OK / rejection / rework for the next process → new tags (OK, one per rejection reason, one per rework reason) are printed.
--  • Supplier processes: a delivery challan (DC) with QR, and a goods-receipt note (GRN) by scanning it; good pieces continue on a new OK tag.
--  • Rejection and rework tags carry the reason code, the specification and the actual measured value (IATF 16949 8.7, ISO 9001 8.7).
--  • Loss hours are booked against D codes (Operations Master › Loss codes); records are never deleted — a wrong entry is voided with a reason (IATF 7.5.3, 8.5.2).
-- Needs 0057 (Operations Master lists for loss codes / reasons / shifts). Safe to re-run. Generated by scripts/make-mmd.py.
-- =====================================================================
