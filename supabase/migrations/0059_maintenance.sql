    if not p_real_only then delete from console.mmd_counters where customer_id = p_cid; end if;
  elsif p_app = 'mnt' then
    delete from console.mmd_loss where customer_id = p_cid and ref is not null and (not p_real_only or sample); get diagnostics k = row_count; n := n + k;
    delete from console.mnt_pm_log where customer_id = p_cid and (not p_real_only or sample); get diagnostics k = row_count; n := n + k;
