    delete from console.sf_lines where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
  elsif p_app = 'calib' then
    delete from console.cal_instruments where customer_id = p_cid and (not p_real_only or not sample); get diagnostics n = row_count;
  elsif p_app = 'apqp' then
    delete from console.apqp_projects where customer_id = p_cid and (not p_real_only or not sample); get diagnostics n = row_count;
  elsif p_app = 'ppap' then
    delete from console.ppap_submissions where customer_id = p_cid and (not p_real_only or not sample); get diagnostics n = row_count;
  elsif p_app = 'rmp' then
    delete from console.rmp_orders where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
    delete from console.rmp_demand where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
    delete from console.rmp_bom where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
    delete from console.rmp_stock where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
  elsif p_app = 'mmd' then
    delete from console.mmd_loss where customer_id = p_cid and (not p_real_only or not sample); get diagnostics k = row_count; n := n + k;
